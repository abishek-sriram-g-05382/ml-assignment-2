"""Streamlit front-end for the frog species classifier.

Loads the five saved pipelines from model/ and scores whatever CSV is
uploaded — never retrains, never calls .fit() on uploaded data.
"""

from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st
from sklearn.metrics import ConfusionMatrixDisplay, classification_report, confusion_matrix

from src.metrics import compute_metrics

APP_DIR = Path(__file__).resolve().parent
MODEL_DIR = APP_DIR / "model"
TEST_CSV = APP_DIR / "test_data.csv"
TARGET_COL = "Species"

MODEL_LABELS = {
    "logistic_regression": "Logistic Regression",
    "decision_tree": "Decision Tree",
    "knn": "KNN",
    "naive_bayes": "Gaussian Naive Bayes",
    "svm": "SVM",
}

st.set_page_config(page_title="Frog Species Classifier", page_icon="🐸", layout="wide")


@st.cache_resource
def load_models() -> dict:
    models = {}
    for name in MODEL_LABELS:
        path = MODEL_DIR / f"{name}.joblib"
        models[name] = joblib.load(path)
    return models


@st.cache_data
def expected_feature_columns() -> list[str]:
    # test_data.csv is the single source of truth for what columns a model
    # expects — it's generated by src/train.py from the same split the
    # models were fit on, so there's no separate list to keep in sync
    header = pd.read_csv(TEST_CSV, nrows=0).columns.tolist()
    return [c for c in header if c != TARGET_COL]


def main():
    st.title("🐸 Frog Species Classifier")
    st.caption("Predicting Anuran species from MFCC call features — upload a test CSV below.")

    models = load_models()

    st.sidebar.header("Settings")
    model_name = st.sidebar.selectbox(
        "Model", options=list(MODEL_LABELS), format_func=lambda k: MODEL_LABELS[k]
    )

    uploaded = st.file_uploader("Upload test CSV", type="csv")

    if uploaded is None:
        st.info("Upload a CSV with the 22 MFCC feature columns plus the Species column to get started.")
        return

    df = pd.read_csv(uploaded)
    st.write(f"Loaded {df.shape[0]} rows, {df.shape[1]} columns.")
    st.dataframe(df.head())

    feature_cols = expected_feature_columns()
    model = models[model_name]

    X = df[feature_cols]
    y_true = df[TARGET_COL]
    y_pred = model.predict(X)
    y_proba = model.predict_proba(X)
    metrics = compute_metrics(y_true, y_pred, y_proba, class_labels=model.classes_)

    st.subheader(f"Metrics — {MODEL_LABELS[model_name]}")
    metrics_row = {k: v for k, v in metrics.items() if k != "best_params"}
    st.dataframe(pd.DataFrame([metrics_row]))

    st.subheader("Confusion matrix")
    labels_sorted = sorted(y_true.unique())
    cm = confusion_matrix(y_true, y_pred, labels=labels_sorted)
    fig, ax = plt.subplots(figsize=(6, 6))
    ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=labels_sorted).plot(
        ax=ax, xticks_rotation=45, colorbar=False
    )
    st.pyplot(fig)

    st.subheader("Classification report")
    report = classification_report(y_true, y_pred, labels=labels_sorted, zero_division=0)
    st.text(report)


if __name__ == "__main__":
    main()
