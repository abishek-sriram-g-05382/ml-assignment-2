"""Streamlit front-end for the frog species classifier.

Loads the five saved pipelines from model/ and scores whatever CSV is
uploaded — never retrains, never calls .fit() on uploaded data.
"""

from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st
from sklearn.metrics import ConfusionMatrixDisplay, classification_report, confusion_matrix

from src.data import clean_columns
from src.metrics import compute_metrics

APP_DIR = Path(__file__).resolve().parent
MODEL_DIR = APP_DIR / "model"
TEST_CSV = APP_DIR / "test_data.csv"
TARGET_COL = "Species"

MODEL_LABELS = {
    "logistic_regression": "Logistic Regression",
    "decision_tree": "Decision Tree",
    "knn": "KNN",
    "naive_bayes": "Gaussian Naive Bayes",
    "svm": "SVM",
}


def _mfcc_description(i: int) -> str:
    # standard MFCC interpretation: low-order coefficients track the broad
    # spectral envelope, higher-order ones track progressively finer detail
    if i == 1:
        return "Overall energy and the broadest shape of the call's frequency spectrum."
    if i <= 6:
        return "Broad spectral envelope — coarse, formant-like shape of the call."
    if i <= 13:
        return "Mid-level spectral detail of the call."
    return "Fine-grained spectral detail and higher-frequency texture of the call."


FEATURE_DESCRIPTIONS = {f"MFCCs_{i}": _mfcc_description(i) for i in range(1, 23)}

st.set_page_config(page_title="Frog Species Classifier", page_icon="🐸", layout="wide")


@st.cache_resource
def load_models() -> dict:
    models = {}
    for name in MODEL_LABELS:
        path = MODEL_DIR / f"{name}.joblib"
        models[name] = joblib.load(path)
    return models


@st.cache_data
def expected_feature_columns() -> list[str]:
    # test_data.csv is the single source of truth for what columns a model
    # expects — it's generated by src/train.py from the same split the
    # models were fit on, so there's no separate list to keep in sync
    header = pd.read_csv(TEST_CSV, nrows=0).columns.tolist()
    return [c for c in header if c != TARGET_COL]


def main():
    st.title("🐸 Frog Species Classifier")
    st.caption("Predicting Anuran species from MFCC call features — upload a test CSV below.")

    models = load_models()

    st.sidebar.header("Settings")
    model_name = st.sidebar.selectbox(
        "Model", options=list(MODEL_LABELS), format_func=lambda k: MODEL_LABELS[k]
    )

    with st.sidebar.expander("Dataset info"):
        info_df = pd.read_csv(TEST_CSV)
        st.write(f"**{len(expected_feature_columns())} MFCC features**, 10 frog species")
        st.write("Species distribution in the bundled held-out test set:")
        st.bar_chart(info_df[TARGET_COL].value_counts())

    with st.sidebar.expander("Feature descriptions"):
        st.dataframe(
            pd.DataFrame(
                {"Feature": FEATURE_DESCRIPTIONS.keys(), "Description": FEATURE_DESCRIPTIONS.values()}
            ),
            hide_index=True,
        )

    uploaded = st.file_uploader("Upload test CSV", type="csv")

    if uploaded is None:
        st.info("Upload a CSV with the 22 MFCC feature columns plus the Species column to get started.")
        return

    try:
        df = pd.read_csv(uploaded)
    except Exception as exc:
        st.error(f"Couldn't read that as a CSV: {exc}")
        return

    # the source dataset ships with inconsistent MFCC header spacing
    # ("MFCCs_ 1" vs "MFCCs_10") — normalize on upload the same way
    # src/data.py does for training, so a CSV built from the raw UCI file
    # isn't rejected over whitespace
    df = clean_columns(df)

    if df.empty:
        st.error("The uploaded CSV has no rows.")
        return

    feature_cols = expected_feature_columns()
    required_cols = [*feature_cols, TARGET_COL]
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        st.error(f"Missing required column(s): {', '.join(missing_cols)}")
        return

    numeric_X = df[feature_cols].apply(pd.to_numeric, errors="coerce")
    bad_rows = numeric_X.isnull().any(axis=1)
    if bad_rows.any():
        st.error(
            f"{bad_rows.sum()} row(s) have a missing or non-numeric value in a "
            "feature column. Fix the CSV and re-upload — the app won't guess "
            "or impute values for you."
        )
        return

    if df[TARGET_COL].isnull().any():
        st.error(f"The {TARGET_COL} column has missing values.")
        return

    st.subheader("Preview of dataset")
    st.caption(f"Loaded {df.shape[0]} rows, {df.shape[1]} columns.")
    st.dataframe(df.head())

    X = numeric_X
    y_true = df[TARGET_COL]

    if y_true.nunique() < 2:
        st.warning(
            "Only one class is present in this file, so AUC and a few other "
            "metrics aren't well-defined — predictions still run below."
        )

    # the brief wants all five models' results visible on the uploaded
    # data, not just whichever one is selected in the dropdown
    st.subheader("All models on this test data")
    predictions = {}  # reused below for whichever model is selected
    comparison = {}
    for name, m in models.items():
        pred = m.predict(X)
        proba = m.predict_proba(X)
        predictions[name] = (pred, proba)
        comparison[MODEL_LABELS[name]] = compute_metrics(y_true, pred, proba, class_labels=m.classes_)
    comparison_df = pd.DataFrame(comparison).T
    st.dataframe(comparison_df)
    st.download_button(
        "Download comparison as CSV",
        comparison_df.to_csv().encode("utf-8"),
        file_name="model_comparison.csv",
        mime="text/csv",
    )

    model = models[model_name]
    y_pred, y_proba = predictions[model_name]
    metrics = compute_metrics(y_true, y_pred, y_proba, class_labels=model.classes_)

    st.subheader(f"Metrics — {MODEL_LABELS[model_name]}")
    metrics_row = {k: v for k, v in metrics.items() if k != "best_params"}
    st.dataframe(pd.DataFrame([metrics_row]))

    st.subheader("Confusion matrix")
    labels_sorted = sorted(y_true.unique())
    cm = confusion_matrix(y_true, y_pred, labels=labels_sorted)
    fig, ax = plt.subplots(figsize=(6, 6))
    ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=labels_sorted).plot(
        ax=ax, xticks_rotation=45, colorbar=False
    )
    st.pyplot(fig)

    st.subheader("Classification report")
    report_dict = classification_report(
        y_true, y_pred, labels=labels_sorted, zero_division=0, output_dict=True
    )
    report_dict.pop("accuracy", None)  # scalar, not a per-row dict — shown above already
    report_df = pd.DataFrame(report_dict).T
    report_df[["precision", "recall", "f1-score"]] = report_df[
        ["precision", "recall", "f1-score"]
    ].round(3)
    report_df["support"] = report_df["support"].astype(int)
    st.dataframe(report_df)

    st.divider()
    st.caption(
        "Dataset: Anuran Calls (MFCCs), UCI Machine Learning Repository. "
        "Models are loaded from model/ and never retrained on uploaded data."
    )


if __name__ == "__main__":
    main()
